export function message(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  const template = (language === "fa" ? fa : en)[key];
  return template.replace(/\{(\w+)\}/g, (token, name: string) => Object.hasOwn(values, name) ? String(values[name]) : token);
}

export function missingMessages(source: Record<string, string>, translated: Record<string, string>): string[] {
  return Object.keys(source).filter((key) => !Object.hasOwn(translated, key) || !translated[key].trim());
}

const sourceKeys = new Map<string, MessageKey>(Object.entries(en).map(([key, value]) => [value, key as MessageKey]));

export function present(language: Language, source: string): string {
  const key = sourceKeys.get(source);
  return key === undefined ? source : message(language, key);
}

export function presentError(language: Language, source: string): string {
  const known = present(language, source);
  return language === "en" || known !== source ? known : `${message(language, "unknownError")}\n${source}`;
}

